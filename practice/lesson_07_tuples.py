# Lesson 7: Tuples

print("Lesson 7A: Tuples Basic")

fruits_tuple = ("apple", "banana", "cherry")

print("Fruits Tuple: ", fruits_tuple)

print("First Fruit: ", fruits_tuple[0])
print("Second Fruit: ", fruits_tuple[1])
print("Third Fruit: ", fruits_tuple[2])

print("Tuple type: ", type(fruits_tuple))

print("Tuple Length: ", len(fruits_tuple))

colors = ("red", "green", "blue")

print("Full colors tuple: ", colors)

print("First color: ", colors[0])
print("Second color: ", colors[1])
print("Third color: ", colors[2])

print("Length of colors tuple: ", len(colors))

print("Type of colors tuple: ", type(colors))
